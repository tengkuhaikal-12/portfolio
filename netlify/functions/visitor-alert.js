import twilio from "twilio";
import { getAdminFirestore } from "./_shared/firebaseAdmin.js";

const APP_CONFIG_COLLECTION = "appConfig";
const VISITOR_ALERT_DOC_ID = "visitorAlerts";

const twilioClient = twilio(
  process.env.TWILIO_ACCOUNT_SID,
  process.env.TWILIO_AUTH_TOKEN
);

const json = (statusCode, payload, headers = {}) => ({
  statusCode,
  headers: { "Content-Type": "application/json; charset=utf-8", ...headers },
  body: JSON.stringify(payload),
});

const getOrigin = (event) =>
  event.headers?.origin ||
  event.headers?.Origin ||
  event.headers?.referer ||
  event.headers?.Referer ||
  "";

const parseAllowedOrigins = () =>
  (process.env.ALLOWED_ORIGINS || "")
    .split(",")
    .map((v) => v.trim())
    .filter(Boolean);

const corsHeadersForOrigin = (origin) => {
  const allowed = parseAllowedOrigins();

  if (!origin) return { "Access-Control-Allow-Origin": "*", Vary: "Origin" };

  if (allowed.length === 0 || allowed.includes(origin)) {
    return { "Access-Control-Allow-Origin": origin, Vary: "Origin" };
  }

  return null;
};

const parseBody = (event) => {
  if (!event.body) return {};
  try {
    const rawBody = event.isBase64Encoded
      ? Buffer.from(event.body, "base64").toString("utf8")
      : event.body;
    return JSON.parse(rawBody);
  } catch {
    return null;
  }
};

function sanitizeString(value, maxLen = 256) {
  return String(value || "").trim().slice(0, maxLen);
}

function formatDuration(ms) {
  const totalSeconds = Math.max(0, Math.round(Number(ms || 0) / 1000));
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = totalSeconds % 60;

  if (minutes <= 0) return `${seconds}s`;
  return `${minutes}m ${seconds}s`;
}

function buildVisitorMessage(payload) {
  const now = new Date();

  const identity =
    sanitizeString(payload.identity, 320) || "Guest";

  const deviceType =
    sanitizeString(payload.device?.deviceType || payload.deviceType, 32) ||
    "unknown";

  const browser =
    sanitizeString(payload.device?.browser || payload.browser, 64) ||
    "Unknown";

  const os =
    sanitizeString(payload.device?.os || payload.os, 64) ||
    "Unknown";

  const startedAt = sanitizeString(payload.startedAt, 80) || "Unknown";
  const endedAt = sanitizeString(payload.endedAt, 80) || now.toLocaleString();
  const duration = formatDuration(payload.durationMs);

  const routes = Array.isArray(payload.routes) ? payload.routes : [];

  const routeText =
    routes.length > 0
      ? routes
        .slice(0, 15)
        .map((route, index) => {
          const path = sanitizeString(route.path, 120) || "Unknown route";
          const timeSpent = formatDuration(route.durationMs);
          const visits = Number(route.visits || 1);

          return `${index + 1}. ${path} — ${timeSpent} (${visits} visit${visits > 1 ? "s" : ""
            })`;
        })
        .join("\n")
      : "No route movement recorded";

  return [
    "🚨 Portfolio Visitor Activity Detected",
    "",
    `👤 Visitor: ${identity}`,
    `💻 Device Type: ${deviceType}`,
    `🌐 Browser: ${browser}`,
    `🖥 Operating System: ${os}`,
    "",
    `🟢 Session Started: ${startedAt}`,
    `🔴 Session Ended: ${endedAt}`,
    `⏱ Total Session Duration: ${duration}`,
    "",
    "📍 Navigation Activity:",
    routeText,
    "",
    "━━━━━━━━━━━━━━━━━━━",
    "Generated by Portfolio Traffic Monitor",
  ].join("\n");
}

async function loadAlertConfig() {
  const firestore = getAdminFirestore();

  const config = {
    telegramBotToken: process.env.TELEGRAM_BOT_TOKEN,
    telegramChatId: process.env.TELEGRAM_CHAT_ID,
    twilioWhatsappFrom: process.env.TWILIO_WHATSAPP_FROM,
    twilioWhatsappTo: process.env.TWILIO_WHATSAPP_TO,
  };

  if (!firestore) return config;

  try {
    const snapshot = await firestore
      .collection(APP_CONFIG_COLLECTION)
      .doc(VISITOR_ALERT_DOC_ID)
      .get();

    const data = snapshot.data() || {};

    return {
      telegramBotToken: data.telegramBotToken || config.telegramBotToken,
      telegramChatId: data.telegramChatId || config.telegramChatId,
      twilioWhatsappFrom:
        data.twilioWhatsappFrom || config.twilioWhatsappFrom,
      twilioWhatsappTo:
        data.twilioWhatsappTo || config.twilioWhatsappTo,
    };
  } catch {
    return config;
  }
}

async function sendTelegramAlert(messageText, config) {
  if (!config.telegramBotToken || !config.telegramChatId) {
    throw new Error("Missing TELEGRAM_BOT_TOKEN or TELEGRAM_CHAT_ID");
  }

  const response = await fetch(
    `https://api.telegram.org/bot${config.telegramBotToken}/sendMessage`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        chat_id: config.telegramChatId,
        text: messageText,
      }),
    }
  );

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Telegram send failed: ${errorText}`);
  }
}

async function sendWhatsappAlert(messageText, config) {
  if (!process.env.TWILIO_ACCOUNT_SID || !process.env.TWILIO_AUTH_TOKEN) {
    throw new Error("Missing TWILIO_ACCOUNT_SID or TWILIO_AUTH_TOKEN");
  }

  if (!config.twilioWhatsappFrom || !config.twilioWhatsappTo) {
    throw new Error("Missing TWILIO_WHATSAPP_FROM or TWILIO_WHATSAPP_TO");
  }

  return twilioClient.messages.create({
    from: config.twilioWhatsappFrom,
    to: config.twilioWhatsappTo,
    body: messageText,
  });
}

export const handler = async (event, context) => {
  if (context) context.callbackWaitsForEmptyEventLoop = false;

  const origin = getOrigin(event);
  const cors = corsHeadersForOrigin(origin);

  if (!cors) return json(403, { error: "CORS blocked" });

  if (event.httpMethod === "OPTIONS") {
    return {
      statusCode: 204,
      headers: {
        ...cors,
        "Access-Control-Allow-Methods": "POST, OPTIONS",
        "Access-Control-Allow-Headers": "Content-Type",
        "Access-Control-Max-Age": "86400",
      },
      body: "",
    };
  }

  if (event.httpMethod !== "POST") {
    return json(405, { error: "Method not allowed" }, cors);
  }

  const body = parseBody(event);
  if (!body) return json(400, { error: "Invalid JSON" }, cors);

  const messageText = buildVisitorMessage(body);

  try {
    const config = await loadAlertConfig();

    const results = await Promise.allSettled([
      sendTelegramAlert(messageText, config),
      sendWhatsappAlert(messageText, config),
    ]);

    const telegram = results[0];
    const whatsapp = results[1];

    return json(
      200,
      {
        ok: telegram.status === "fulfilled" || whatsapp.status === "fulfilled",
        telegram:
          telegram.status === "fulfilled"
            ? "sent"
            : telegram.reason?.message || "failed",
        whatsapp:
          whatsapp.status === "fulfilled"
            ? "sent"
            : whatsapp.reason?.message || "failed",
      },
      cors
    );
  } catch (error) {
    console.error("Visitor alert failed:", error?.message || error);

    return json(
      500,
      {
        error: "Failed to send visitor alert",
        detail: error?.message || String(error),
      },
      cors
    );
  }
};